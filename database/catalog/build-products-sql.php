<?php
declare(strict_types=1);

/**
 * Builds database/catalog/products.sql from the live product table.
 *
 * Usage:
 *   php database/catalog/build-products-sql.php                       # every product
 *   php database/catalog/build-products-sql.php --category "Dog Food"  # one category
 *
 * The file it writes is what import.php reads, so this is the only place that decides how a
 * product row is turned into SQL. Upserts are keyed on SKU.
 */

require_once __DIR__ . '/../../includes/data.php';

$categoryFilter = null;
foreach ($argv as $index => $argument) {
    if ($argument === '--category' && isset($argv[$index + 1])) {
        $categoryFilter = trim((string) $argv[$index + 1]);
    }
}

$sql = 'SELECT p.*, c.name AS category_name FROM products p INNER JOIN categories c ON c.id = p.category_id';
$params = [];
if ($categoryFilter !== null) {
    $sql .= ' WHERE c.name = ?';
    $params[] = $categoryFilter;
}
$sql .= ' ORDER BY c.name ASC, p.brand ASC, p.name ASC';
$rows = db_all($sql, $params);
if ($rows === []) {
    fwrite(STDERR, "No products matched. Nothing written.\n");
    exit(1);
}

$columns = [
    'category_id', 'brand', 'name', 'description', 'price', 'currency', 'price_type', 'price_source',
    'source_price', 'source_currency', 'source_exchange_rate', 'price_checked_on', 'discount', 'sku',
    'stock_quantity', 'low_stock_threshold', 'stock_type', 'stock_source', 'rating', 'review_count',
    'rating_type', 'image', 'image_url', 'image_alt', 'source_url', 'image_source_name', 'image_source_url', 'status',
];
$updatable = array_values(array_diff($columns, ['category_id', 'sku']));

$quote = static function (mixed $value): string {
    if ($value === null) {
        return 'NULL';
    }
    if (is_bool($value)) {
        return $value ? '1' : '0';
    }
    return "'" . str_replace(["\\", "'"], ["\\\\", "''"], (string) $value) . "'";
};

// Only these columns are numbers in the schema. Everything else is quoted, because a bare
// identifier such as 023100143538 would be read back by MariaDB as the number 23100143538.
$numericColumns = [
    'price', 'discount', 'stock_quantity', 'low_stock_threshold',
    'rating', 'review_count', 'source_price', 'source_exchange_rate',
];

$format = static function (mixed $value) use ($quote): string {
    if ($value === null) {
        return 'NULL';
    }
    if (is_bool($value)) {
        return $value ? '1' : '0';
    }
    return $quote($value);
};

$categoryNames = [];
foreach (db_all('SELECT id, name FROM categories') as $row) {
    $categoryNames[(int) $row['id']] = (string) $row['name'];
}

$header = "-- PAWORA product catalog data.\n"
    . "-- Generated by database/catalog/build-products-sql.php and read by database/catalog/import.php.\n"
    . "-- Every value is escaped and rows upsert on the unique SKU, so re-importing is safe.\n"
    . '-- Rows: ' . count($rows) . ($categoryFilter !== null ? ' (category: ' . $categoryFilter . ')' : '') . "\n"
    . "-- category_id is resolved from the category names in categories.sql at import time.\n\n"
    . "START TRANSACTION;\n\n";

$out = $header;
$currentCategory = null;
foreach ($rows as $row) {
    $categoryName = (string) ($categoryNames[(int) $row['category_id']] ?? $row['category_name']);
    if ($categoryName !== $currentCategory) {
        $currentCategory = $categoryName;
        $out .= "\n-- ============ " . $currentCategory . " ============\n";
    }
    $values = [];
    foreach ($columns as $column) {
        $value = $row[$column] ?? null;
        if ($column === 'category_id') {
            $values[] = "(SELECT id FROM categories WHERE name = " . $quote($categoryName) . ' LIMIT 1)';
            continue;
        }
        $values[] = in_array($column, $numericColumns, true) && $value !== null
            ? (string) $value
            : $format($value);
    }
    $out .= 'INSERT INTO products (' . implode(', ', $columns) . ") VALUES (\n    "
        . implode(",\n    ", $values) . "\n)\nON DUPLICATE KEY UPDATE\n    "
        . implode(",\n    ", array_map(static fn (string $column): string => $column . ' = VALUES(' . $column . ')', $updatable))
        . ";\n";
}
$out .= "\nCOMMIT;\n";

$target = __DIR__ . '/products.sql';
file_put_contents($target, $out);
echo 'wrote database/catalog/products.sql (' . count($rows) . ' products, ' . number_format(strlen($out)) . " bytes)\n";
